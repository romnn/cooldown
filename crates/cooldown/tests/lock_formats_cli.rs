//! Exercises how the CLI treats lockfile formats an adapter cannot read.

use color_eyre::eyre;
use indoc::indoc;
use std::process::Command;

/// A Yarn Berry project whose `yarn.lock` the Classic reader cannot parse.
fn berry_project() -> eyre::Result<tempfile::TempDir> {
    let directory = tempfile::tempdir()?;
    std::fs::write(
        directory.path().join("package.json"),
        indoc! {r#"
            {
              "name": "berry-app",
              "version": "1.0.0",
              "packageManager": "yarn@4.5.0",
              "dependencies": { "lodash": "^4.17.21" }
            }
        "#},
    )?;
    std::fs::write(
        directory.path().join("yarn.lock"),
        indoc! {r#"
            # This file is generated by running "yarn install" inside your project.
            # Manual changes might be lost - proceed with caution!

            __metadata:
              version: 8
              cacheKey: 10c0

            "berry-app@workspace:.":
              version: 0.0.0-use.local
              resolution: "berry-app@workspace:."
              dependencies:
                lodash: "npm:^4.17.21"
              languageName: unknown
              linkType: soft

            "lodash@npm:^4.17.21":
              version: 4.17.21
              resolution: "lodash@npm:4.17.21"
              languageName: node
              linkType: hard
        "#},
    )?;
    Ok(directory)
}

/// Runs cooldown in `directory` with `args`, returning the exit code and the JSON envelope.
fn cooldown_json(
    directory: &tempfile::TempDir,
    args: &[&str],
) -> eyre::Result<(Option<i32>, serde_json::Value)> {
    let output = Command::new(env!("CARGO_BIN_EXE_cooldown"))
        .current_dir(directory.path())
        .args(args)
        .args(["--json", "--no-progress"])
        .output()?;
    let document = serde_json::from_slice(&output.stdout).map_err(|err| {
        eyre::eyre!(
            "cooldown {args:?} printed no JSON envelope ({err}); stderr: {}",
            String::from_utf8_lossy(&output.stderr)
        )
    })?;
    Ok((output.status.code(), document))
}

/// The error kinds an envelope reports, in order.
fn error_kinds(document: &serde_json::Value) -> Vec<String> {
    document
        .pointer("/errors")
        .and_then(serde_json::Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(|error| error.pointer("/kind").and_then(serde_json::Value::as_str))
        .map(ToString::to_string)
        .collect()
}

/// A Berry lock is reported as unreadable, never read as an empty graph that leaves `outdated`
/// with nothing to report and `upgrade` with nothing to do.
#[test]
fn a_yarn_berry_lock_is_reported_unreadable() -> eyre::Result<()> {
    let project = berry_project()?;

    let (_, outdated) = cooldown_json(&project, &["outdated", "--offline"])?;
    assert_eq!(
        error_kinds(&outdated),
        ["lockfile_unreadable"],
        "outdated envelope: {outdated:#}"
    );
    let message = outdated
        .pointer("/errors/0/message")
        .and_then(serde_json::Value::as_str)
        .unwrap_or_default();
    assert!(message.contains("Yarn Berry"), "message: {message}");

    // The refusal comes from reading the lock, before the dry run would reach a registry.
    let (code, upgrade) = cooldown_json(&project, &["upgrade", "--dry-run"])?;
    assert_eq!(
        error_kinds(&upgrade),
        ["lockfile_unreadable"],
        "upgrade envelope: {upgrade:#}"
    );
    assert_eq!(code, Some(4), "upgrade envelope: {upgrade:#}");
    assert_eq!(
        upgrade.pointer("/ok").and_then(serde_json::Value::as_bool),
        Some(false)
    );
    Ok(())
}
