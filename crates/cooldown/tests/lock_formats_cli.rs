/// A Berry project whose `yarn.lock` is `lock`, anchored as its own Git repository so no ambient
/// config above the temporary directory is read.
fn berry_project(lock: &str) -> eyre::Result<tempfile::TempDir> {
    let directory = tempfile::tempdir()?;
    let root = directory.path();
    std::fs::create_dir_all(root.join(".git"))?;
    std::fs::write(root.join(".git/HEAD"), "ref: refs/heads/main\n")?;
    std::fs::create_dir_all(root.join("packages/app"))?;
    std::fs::create_dir_all(root.join("local"))?;
    std::fs::write(root.join("package.json"), BERRY_MANIFEST)?;
    std::fs::write(
        root.join("packages/app/package.json"),
        BERRY_MEMBER_MANIFEST,
    )?;
    std::fs::write(root.join("yarn.lock"), lock)?;
    Ok(directory)
}

/// Runs cooldown in `directory` with `args` against an empty cache, returning the exit code and
/// the JSON envelope.
fn cooldown_json(
    directory: &tempfile::TempDir,
    args: &[&str],
) -> eyre::Result<(Option<i32>, serde_json::Value)> {
    // An empty cache keeps `--offline` from answering any release, so the run stays hermetic and
    // every row it reports comes from the lock alone.
    let cache = tempfile::tempdir()?;
    let output = Command::new(env!("CARGO_BIN_EXE_cooldown"))
        .current_dir(directory.path())
        .env("XDG_CACHE_HOME", cache.path())
        .args(args)
        .args(["--json", "--no-progress"])
        .output()?;
    let document = serde_json::from_slice(&output.stdout).map_err(|err| {
        eyre::eyre!(
            "cooldown {args:?} printed no JSON envelope ({err}); stderr: {}",
            String::from_utf8_lossy(&output.stderr)
        )
    })?;
    Ok((output.status.code(), document))
}

/// The values of the string field `field` across the envelope's `section` array, in order.
fn fields(document: &serde_json::Value, section: &str, field: &str) -> Vec<String> {
    document
        .get(section)
        .and_then(serde_json::Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(|entry| entry.get(field).and_then(serde_json::Value::as_str))
        .map(ToString::to_string)
        .collect()
}

/// One inventoried row: `name@current`, with ` direct` for a direct dependency.
fn inventory(document: &serde_json::Value) -> BTreeSet<String> {
    document
        .pointer("/items")
        .and_then(serde_json::Value::as_array)
        .into_iter()
        .flatten()
        .map(|item| {
            let field = |key: &str| {
                item.get(key)
                    .and_then(serde_json::Value::as_str)
                    .unwrap_or_default()
            };
            let direct = if item.get("direct").and_then(serde_json::Value::as_bool) == Some(true) {
                " direct"
            } else {
                ""
            };
            format!("{}@{}{direct}", field("name"), field("current"))
        })
        .collect()
}

/// A Berry lock is read for its registry releases: every npm locator is a row, under the alias
/// target's own name, while the workspaces and the `link:` package are none, and the root's own
/// declarations are its direct rows.
/// The member's dependency reads as transitive, which the run warns about.
#[test]
fn a_yarn_berry_lock_is_inventoried() -> eyre::Result<()> {
    let project = berry_project(BERRY_LOCK)?;

    let (code, outdated) = cooldown_json(
        &project,
        &["outdated", "--offline", "--transitive", "--all"],
    )?;

    assert_eq!(code, Some(0), "outdated envelope: {outdated:#}");
    assert_eq!(
        inventory(&outdated),
        BTreeSet::from(
            [
                "@sindresorhus/is@4.6.0 direct",
                "ansi-styles@4.3.0",
                "chalk@4.1.2 direct",
                "color-convert@2.0.1",
                "color-name@1.1.4",
                "has-flag@4.0.0",
                "is-number@6.0.0",
                "supports-color@7.2.0",
            ]
            .map(str::to_string)
        ),
        "outdated envelope: {outdated:#}"
    );
    // Every row reached evaluation and missed only the empty offline cache.
    assert!(
        fields(&outdated, "errors", "kind").is_empty(),
        "{outdated:#}"
    );
    assert_eq!(fields(&outdated, "warnings", "kind"), ["config"]);
    let warnings = fields(&outdated, "warnings", "message");
    assert!(
        warnings
            .iter()
            .all(|message| message.contains("workspace members cooldown does not attribute yet")),
        "{warnings:?}"
    );
    Ok(())
}

/// A malformed Berry lock and one of a schema no released Yarn wrote are reported as
/// unreadable, never read as an empty graph that leaves `outdated` with nothing to report and
/// `upgrade` with nothing to do.
#[test]
fn unreadable_yarn_berry_locks_are_reported() -> eyre::Result<()> {
    let malformed = BERRY_LOCK.replacen("  resolution: \"chalk@npm:4.1.2\"\n", "", 1);
    let unsupported = BERRY_LOCK.replacen("  version: 10\n", "  version: 11\n", 1);
    for (case, lock, detail) in [
        ("malformed", malformed, "records no `resolution`"),
        (
            "unsupported",
            unsupported,
            "unsupported Yarn Berry lockfile version 11",
        ),
    ] {
        let project = berry_project(&lock)?;

        let (_, outdated) = cooldown_json(&project, &["outdated", "--offline"])?;
        assert_eq!(
            fields(&outdated, "errors", "kind"),
            ["lockfile_unreadable"],
            "{case}: outdated envelope: {outdated:#}"
        );
        let messages = fields(&outdated, "errors", "message");
        assert!(
            messages
                .iter()
                .all(|message| message.contains("yarn.lock:") && message.contains(detail)),
            "{case}: {messages:?}"
        );

        // The refusal comes from reading the lock, before the dry run would reach a registry.
        let (code, upgrade) = cooldown_json(&project, &["upgrade", "--dry-run"])?;
        assert_eq!(
            fields(&upgrade, "errors", "kind"),
            ["lockfile_unreadable"],
            "{case}: upgrade envelope: {upgrade:#}"
        );
        assert_eq!(code, Some(4), "{case}: upgrade envelope: {upgrade:#}");
        assert_eq!(
            upgrade.pointer("/ok").and_then(serde_json::Value::as_bool),
            Some(false),
            "{case}"
        );
    }
    Ok(())
}
