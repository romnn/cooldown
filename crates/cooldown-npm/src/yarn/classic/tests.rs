/// A published landing that a settled-lock guard rejects is rolled back from exactly what it
/// wrote: the seeded install also moved the root's exact pin of `leaf`, which nothing asked to
/// rewrite, so the lock returns to the one the landing started from.
#[tokio::test]
async fn a_rejected_landing_rolls_back_from_what_it_published() -> eyre::Result<()> {
    let leaf = |version: &str| {
        formatdoc! {r#"

            leaf@1.0.0:
              version "{version}"
              resolved "https://registry.yarnpkg.com/leaf/-/leaf-{version}.tgz"
        "#}
    };
    let manifest = MANIFEST.replace(
        r#""chalk": "^4.0.0""#,
        r#""chalk": "^4.0.0", "leaf": "1.0.0""#,
    );
    let starting = format!("{STARTING}{}", leaf("1.0.0"));
    let world = new_world(&[("package.json", &manifest)], &starting)?;
    world.answer("lock1", &format!("{PINNED}{}", leaf("1.0.0")))?;
    world.answer("lock2", &format!("{SETTLED}{}", leaf("1.1.0")))?;

    let report = world
        .apply(&plan_of(chalk_change("4.0.0", &["."])))
        .await??;

    let [held] = report.skipped.as_slice() else {
        eyre::bail!("expected one rolled-back row: {report:?}");
    };
    assert_eq!(held.reason, SkipReason::ResolverConflict);
    let detail = held.detail.as_deref().unwrap_or_default();
    assert!(detail.contains("exact pin"), "{detail}");
    assert_eq!(world.lock()?, starting);
    Ok(())
}

