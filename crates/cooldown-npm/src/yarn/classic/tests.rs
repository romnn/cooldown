/// A landing reports what it moved per selector: `leaf@^1.0.0` moving while `leaf@^2.0.0` stays
/// the newest copy is a collateral row of its own.
#[tokio::test]
async fn a_selector_moved_beside_a_newer_copy_is_reported() -> eyre::Result<()> {
    let leaf = |one: &str| {
        formatdoc! {r#"

            leaf@^1.0.0:
              version "{one}"

            leaf@^2.0.0:
              version "2.0.0"
        "#}
    };
    let starting = format!("{STARTING}{}", leaf("1.0.0"));
    let world = new_world(&[("package.json", MANIFEST)], &starting)?;
    world.answer("lock2", &format!("{SETTLED}{}", leaf("1.1.0")))?;

    let report = world
        .apply(&plan_of(chalk_change("4.0.0", &["."])))
        .await??;

    let moves: Vec<String> = report
        .applied
        .iter()
        .map(|change| format!("{}@{}->{}", change.package.name, change.from, change.to))
        .collect();
    assert_eq!(moves, ["chalk@4.0.0->4.1.0", "leaf@1.0.0->1.1.0"]);
    Ok(())
}

/// Only a range that admits the target can be seeded: Yarn would reuse whatever entry seeding gave
/// a protocol reference, whose release it never checks against a range.
#[test]
fn a_selector_that_admits_no_target_cannot_be_seeded() -> eyre::Result<()> {
    let directory = tempfile::tempdir()?;
    let root = Utf8PathBuf::from_path_buf(directory.path().to_path_buf())
        .map_err(|path| eyre::eyre!("temporary path is not UTF-8: {}", path.display()))?;
    write(
        &root.join("package.json"),
        r#"{ "dependencies": { "chalk": "npm:chalk@^4.0.0" } }"#,
    )?;
    let workspace = WorkspaceManifests::read(&root, WorkspaceDialect::Classic);

    let refused = selectors(&workspace, &chalk_change("4.0.0", &["."]));

    assert_eq!(
        refused,
        Err(". declares chalk as `npm:chalk@^4.0.0`, no range that admits 4.1.0".to_string())
    );
    Ok(())
}

/// Yarn's default cache folder is granted only where it resolves outside the project: one inside
/// the project, one reached through a link into it, and one that holds it are not, and none is
/// created there.
#[test]
fn the_cache_is_granted_only_outside_the_project() -> eyre::Result<()> {
    let guard = tempfile::tempdir()?;
    let top = Utf8PathBuf::from_path_buf(dunce::canonicalize(guard.path())?)
        .map_err(|path| eyre::eyre!("temporary path is not UTF-8: {}", path.display()))?;
    let root = top.join("project");
    std::fs::create_dir_all(root.join(".cache"))?;
    let environment = |home: Utf8PathBuf, xdg_cache_home: Option<Utf8PathBuf>| YarnEnvironment {
        home: Some(home),
        xdg_cache_home,
        ..YarnEnvironment::default()
    };

    // Outside the project, created when missing
    let home = top.join("home");
    std::fs::create_dir_all(home.join(".cache"))?;
    assert_eq!(
        yarn_cache(&environment(home.clone(), None), &root),
        Some(home.join(".cache/yarn"))
    );
    assert!(home.join(".cache/yarn").is_dir());

    // Inside the project
    let inside = environment(home.clone(), Some(root.join(".cache")));
    assert_eq!(yarn_cache(&inside, &root), None);
    // Through a link into the project, above the folder or at it
    let linked = top.join("linked");
    std::fs::create_dir_all(&linked)?;
    std::os::unix::fs::symlink(root.join(".cache"), linked.join(".cache"))?;
    assert_eq!(yarn_cache(&environment(linked, None), &root), None);
    assert!(!root.join(".cache/yarn").exists());
    let linked = top.join("linked-folder");
    std::fs::create_dir_all(linked.join(".cache"))?;
    std::os::unix::fs::symlink(root.join(".cache"), linked.join(".cache/yarn"))?;
    assert_eq!(yarn_cache(&environment(linked, None), &root), None);

    // Holding the project
    let held = top.join("caches/yarn/project");
    std::fs::create_dir_all(&held)?;
    let holding = environment(home, Some(top.join("caches")));
    assert_eq!(yarn_cache(&holding, &held), None);
    Ok(())
}
