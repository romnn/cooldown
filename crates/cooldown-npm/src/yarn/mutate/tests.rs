fn only_a_new_release_beside_the_target_is_ungated() -> eyre::Result<()> {
    let gate = NativeGate {
        preapproved: Vec::new(),
        minutes: 1440,
        scopes: BTreeMap::from([("corp".to_string(), 1440)]),
    };
    let entry = |name: &str, version: &str| {
        formatdoc! {r#"

            "{name}@npm:^1.0.0":
              version: {version}
              resolution: "{name}@npm:{version}"
              languageName: node
              linkType: hard
        "#}
    };
    let started = format!("{STARTING}{}", entry("@corp/tool", "1.0.0"));
    let target = format!("{STARTING}{}", entry("@corp/tool", "1.1.0"));
    let beside = format!("{target}{}", entry("@corp/child", "1.2.0"));

    assert_eq!(
        gate.ungated_release(&started, &target, "@corp/tool@1.1.0", 10080)?,
        None
    );
    assert_eq!(
        gate.ungated_release(&started, &beside, "@corp/tool@1.1.0", 10080)?
            .as_deref(),
        Some("@corp/child@1.2.0")
    );
    assert_eq!(
        gate.ungated_release(&started, &beside, "@corp/tool@1.1.0", 1440)?,
        None
    );
    Ok(())
}

/// A runner whose hold and failure details quote a credentialed registry URL, as a declaration
/// or Yarn's output can.
struct Credentialed {
    hold: bool,
}

/// A URL carrying a password and a token, which no row may print.
const CREDENTIALED: &str =
    "https://user:hunter2@npm.corp.example/chalk/-/chalk-4.1.1.tgz?token=s3cr3t";

#[async_trait::async_trait]
impl CandidateRunner for Credentialed {
    fn hold(
        &self,
        _project: &Project,
        _plan: &Plan,
        change: &Change,
        _lock: Option<&str>,
    ) -> cooldown_core::Result<Option<Skipped>> {
        Ok(self.hold.then(|| Skipped {
            change: change.clone(),
            reason: SkipReason::NotEligible,
            offending: None,
            detail: Some(format!("held at {CREDENTIALED}")),
        }))
    }

    fn skip_detail(&self, _error: &CoreError) -> Option<String> {
        Some(format!("failed at {CREDENTIALED}"))
    }

    async fn land(
        &self,
        _project: &Project,
        _change: &Change,
        _candidate_journal: &cooldown_core::ProjectMutationJournal,
        _landing: &CandidateLanding,
        authorized: &cooldown_core::ProjectMutationState,
    ) -> cooldown_core::Result<OwnedStep> {
        Ok(OwnedStep {
            result: Err(CoreError::UnacceptableResolve(CREDENTIALED.to_string())),
            postimage: authorized.clone(),
        })
    }
}

