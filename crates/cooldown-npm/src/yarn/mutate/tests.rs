/// A runner whose hold finds the project's lock replaced by someone else, as a concurrent edit
/// during the hold's own reads would.
struct ReplacedDuringHold {
    lock: Utf8PathBuf,
    replacement: String,
}

#[async_trait::async_trait]
impl CandidateRunner for ReplacedDuringHold {
    fn hold(
        &self,
        _project: &Project,
        _plan: &Plan,
        change: &Change,
        _lock: Option<&str>,
    ) -> cooldown_core::Result<Option<Skipped>> {
        std::fs::write(&self.lock, &self.replacement)?;
        Ok(Some(Skipped {
            change: change.clone(),
            reason: SkipReason::NotEligible,
            offending: None,
            detail: None,
        }))
    }

    async fn land(
        &self,
        _project: &Project,
        _change: &Change,
        _candidate_journal: &cooldown_core::ProjectMutationJournal,
        _landing: &CandidateLanding,
        _authorized: &cooldown_core::ProjectMutationState,
    ) -> cooldown_core::Result<OwnedStep> {
        Err(CoreError::System("a held candidate never lands".into()))
    }
}

/// A held candidate rolls back from the state cooldown's own edits left, captured before the
/// hold read anything, so a lock someone else replaced meanwhile is refused as a conflict rather
/// than restored over.
#[tokio::test]
async fn a_hold_never_restores_over_a_concurrent_edit() -> eyre::Result<()> {
    let world = single_world()?;
    let replacement = format!("{STARTING}\n# edited elsewhere\n");
    let mutation = PreparedMutation::prepare(&world.tool, &world.project, &chalk_plan()).await?;
    let runner = ReplacedDuringHold {
        lock: world.project.root.join("yarn.lock"),
        replacement: replacement.clone(),
    };

    let applied = world.tool.berry.apply_with_runner(&mutation, &runner).await;

    assert!(
        matches!(&applied, Err(CoreError::LockConflict(_))),
        "{applied:?}"
    );
    assert_eq!(world.lock()?, replacement);
    Ok(())
}
