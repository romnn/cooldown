/// A Berry project, its home directory and scratch base, and a fake `yarn` whose answers live in
/// files beside it.
struct World {
    /// Owns every directory of the world; dropping it deletes them.
    _guard: tempfile::TempDir,
    top: Utf8PathBuf,
    project: Project,
    /// Owns the adapter's HTTP cache.
    _cache: tempfile::TempDir,
    tool: YarnTool,
}

/// The fake `yarn`.
///
/// Each run appends `cwd|args|preapproved|gate|global` to `yarn.log`.
/// `--version` prints `version`; a verification prints `verify.ndjson`, or `verify-after.ndjson`
/// once a landing installed; `config --json` prints `config.ndjson`, and `config get` prints
/// `scopes.json`.
/// Install `n` saves the manifest and lock it ran on as `seen<n>.json` and `seen<n>.lock`, runs
/// `meddle<n>` when it exists, fails with `fail<n>` when it exists, and otherwise writes
/// `lock<n>` as the lock, a reformatted manifest, and install state, as Yarn does.
fn fake_yarn(top: &Utf8Path) -> String {
    formatdoc! {r#"
        #!/bin/sh
        echo "$PWD|$*|$YARN_NPM_PREAPPROVED_PACKAGES|$YARN_NPM_MINIMAL_AGE_GATE|$YARN_GLOBAL_FOLDER" >> "{top}/yarn.log"
        case "$1" in
          --version) cat "{top}/version" ;;
          config)
            if [ "$2" = get ]; then cat "{top}/scopes.json"; else cat "{top}/config.ndjson"; fi ;;
          install)
            case "$2 $3" in
              "--immutable --mode=skip-build")
                if [ -e "{top}/installs" ] && [ -e "{top}/verify-after.ndjson" ]; then
                  cat "{top}/verify-after.ndjson"
                else
                  cat "{top}/verify.ndjson"
                fi
                exit 1 ;;
              "--immutable ") exit 0 ;;
            esac
            n=$(( $(cat "{top}/installs" 2>/dev/null || echo 0) + 1 ))
            echo "$n" > "{top}/installs"
            cp package.json "{top}/seen$n.json"
            cp yarn.lock "{top}/seen$n.lock"
            if [ -e "{top}/meddle$n" ]; then sh "{top}/meddle$n"; fi
            if [ -e "{top}/fail$n" ]; then cat "{top}/fail$n"; exit 1; fi
            cp "{top}/lock$n" yarn.lock
            echo '{{"reformatted": true}}' > package.json
            mkdir -p .yarn && echo state > .yarn/install-state.gz
            ;;
        esac
    "#}
}

fn new_world(manifests: &[(&str, &str)], lock: &str) -> eyre::Result<World> {
    use std::os::unix::fs::PermissionsExt as _;
    let guard = tempfile::tempdir()?;
    let top = Utf8PathBuf::from_path_buf(dunce::canonicalize(guard.path())?)
        .map_err(|path| eyre::eyre!("temporary path is not UTF-8: {}", path.display()))?;
    let root = top.join("project");
    for (path, contents) in manifests {
        write(&root.join(path), contents)?;
    }
    write(&root.join("yarn.lock"), lock)?;
    let home = top.join("home");
    std::fs::create_dir_all(&home)?;
    let script = top.join("fake-yarn.sh");
    std::fs::write(&script, fake_yarn(&top))?;
    std::fs::set_permissions(&script, std::fs::Permissions::from_mode(0o755))?;
    for (file, contents) in [
        ("version", "4.18.1\n"),
        ("verify.ndjson", CURRENT),
        ("lock1", PINNED),
        ("lock2", SETTLED),
    ] {
        std::fs::write(top.join(file), contents)?;
    }
    Config::defaults(&top).write(&top)?;
    let cache = tempfile::tempdir()?;
    let tool = YarnTool::from_http(SharedHttp::new(cache.path(), HttpOptions::default())?)
        .with_driver(script.as_str())
        .with_verification(
            YarnEnvironment {
                home: Some(home),
                ..YarnEnvironment::default()
            },
            vec![top.join("tmp")],
        );
    Ok(World {
        _guard: guard,
        project: Project::detected(root.clone(), Yarn::ID, root.join("package.json")),
        top,
        _cache: cache,
        tool,
    })
}

/// The settings the fake's `config --json` and `config get npmScopes --json` report.
struct Config {
    global: String,
    preapproved: serde_json::Value,
    gate: u64,
    scopes: serde_json::Value,
}

impl Config {
    /// Yarn's defaults, its global folder below `top`.
    fn defaults(top: &Utf8Path) -> Self {
        Config {
            global: format!("{top}/global"),
            preapproved: serde_json::json!([]),
            gate: 1440,
            scopes: serde_json::json!({}),
        }
    }

    /// Writes both reports into `top` as Yarn 4.18.1 prints them.
    fn write(&self, top: &Utf8Path) -> eyre::Result<()> {
        let unset = self
            .scopes
            .as_object()
            .is_some_and(serde_json::Map::is_empty);
        let lines = [
            serde_json::json!({ "key": "globalFolder", "effective": self.global, "source": "<default>" }),
            serde_json::json!({ "key": "npmPreapprovedPackages", "effective": self.preapproved, "source": "<default>" }),
            serde_json::json!({ "key": "npmMinimalAgeGate", "effective": self.gate, "source": "<default>" }),
            // The full report leaves out a map no source sets and spells any other as `{}`.
            if unset {
                serde_json::json!({ "key": "npmScopes", "source": "<default>" })
            } else {
                serde_json::json!({ "key": "npmScopes", "effective": {}, "source": "/project/.yarnrc.yml" })
            },
        ]
        .map(|line| line.to_string());
        std::fs::write(top.join("config.ndjson"), lines.join("\n") + "\n")?;
        let scopes = if unset {
            "undefined".to_string()
        } else {
            self.scopes.to_string()
        };
        std::fs::write(top.join("scopes.json"), scopes + "\n")?;
        Ok(())
    }
}

/// A world of the single-package project at its starting lock.
fn single_world() -> eyre::Result<World> {
    new_world(&[("package.json", MANIFEST)], STARTING)
}

/// One run the fake logged.
#[derive(Debug)]
struct Run {
    directory: String,
    args: String,
    preapproved: String,
    gate: String,
    global: String,
}

impl World {
    fn answer(&self, file: &str, contents: &str) -> eyre::Result<()> {
        std::fs::write(self.top.join(file), contents)?;
        Ok(())
    }

    fn read(&self, file: &str) -> eyre::Result<String> {
        Ok(std::fs::read_to_string(self.top.join(file))?)
    }

    fn runs(&self) -> eyre::Result<Vec<Run>> {
        let log = std::fs::read_to_string(self.top.join("yarn.log")).unwrap_or_default();
        log.lines()
            .map(|line| {
                let fields: Vec<&str> = line.split('|').collect();
                let [directory, args, preapproved, gate, global] = fields.as_slice() else {
                    eyre::bail!("malformed log line {line}");
                };
                Ok(Run {
                    directory: (*directory).to_string(),
                    args: (*args).to_string(),
                    preapproved: (*preapproved).to_string(),
                    gate: (*gate).to_string(),
                    global: (*global).to_string(),
                })
            })
            .collect()
    }

    /// The lock-only installs the fake ran.
    fn installs(&self) -> eyre::Result<Vec<Run>> {
        Ok(self
            .runs()?
            .into_iter()
            .filter(|run| run.args.starts_with("install --mode=update-lockfile"))
            .collect())
    }

    fn lock(&self) -> eyre::Result<String> {
        Ok(std::fs::read_to_string(
            self.project.root.join("yarn.lock"),
        )?)
    }

    /// Prepares and applies `plan` through the observed entry point the executor uses.
    async fn apply(&self, plan: &Plan) -> eyre::Result<cooldown_core::Result<ApplyReport>> {
        /// An observer that ignores every notification.
        struct Silent;
        impl cooldown_core::ApplyObserver for Silent {}

        let mutation = PreparedMutation::prepare(&self.tool, &self.project, plan).await?;
        let attempt = self.tool.apply_with_observer(&mutation, &Silent).await?;
        match attempt.into_outcome_for(&mutation)? {
            cooldown_core::ApplyAttemptOutcome::Finished { report, .. } => Ok(report),
            other @ cooldown_core::ApplyAttemptOutcome::PendingRecovery { .. } => {
                eyre::bail!("expected a finished attempt, got {other:?}")
            }
        }
    }
}

fn write(path: &Utf8Path, contents: &str) -> eyre::Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, contents)?;
    Ok(())
}

/// Every file below `root` with its bytes, the lock left out.
fn files_beside_the_lock(root: &Utf8Path) -> eyre::Result<BTreeMap<String, Vec<u8>>> {
    let mut files = BTreeMap::new();
    let mut directories = vec![root.to_path_buf()];
    while let Some(directory) = directories.pop() {
        for entry in std::fs::read_dir(&directory)? {
            let entry = entry?;
            let path = Utf8PathBuf::from_path_buf(entry.path())
                .map_err(|path| eyre::eyre!("path is not UTF-8: {}", path.display()))?;
            if entry.file_type()?.is_dir() {
                directories.push(path);
            } else if path.file_name() != Some("yarn.lock") {
                let relative = path.strip_prefix(root)?.to_string();
                files.insert(relative, std::fs::read(&path)?);
            }
        }
    }
    Ok(files)
}

/// The change moving the root's `chalk` from 4.1.0 to 4.1.1.
fn chalk_change() -> Change {
    Change {
        package: PackageId::new(Yarn::ID, "chalk", Some(NPM.to_string())),
        from: Version::new("4.1.0"),
        to: Version::new("4.1.1"),
        kind: UpdateKind::Patch,
        downgrade: false,
        direct: true,
        members: vec![MemberRef {
            name: "berry-land".to_string(),
            path: ".".to_string(),
        }],
    }
}

fn chalk_plan() -> Plan {
    Plan {
        changes: vec![chalk_change()],
        ..Plan::default()
    }
}

/// The landing pins the target exactly in a copy, resolves it under an approval of exactly that
/// release, restores the authorized manifest and seeds `^4.0.0` into the pinned release's key
/// before resolving again, has Yarn prove the result current in the copy, and writes back only
/// the lock: the project's manifest stays byte for byte and no install state reaches it.
#[tokio::test]
async fn a_landing_resolves_in_a_copy_and_writes_back_only_the_lock() -> eyre::Result<()> {
    let world = single_world()?;
    Config {
        preapproved: serde_json::json!(["left-pad"]),
        ..Config::defaults(&world.top)
    }
    .write(&world.top)?;
    let before = files_beside_the_lock(&world.project.root)?;

    let report = world.apply(&chalk_plan()).await??;

    assert_eq!(report.applied.len(), 1, "{report:?}");
    assert!(report.skipped.is_empty(), "{report:?}");
    assert_eq!(world.lock()?, SETTLED);
    assert_eq!(files_beside_the_lock(&world.project.root)?, before);

    // The pinned install read the exact pin, the seeded one the authorized range and a lock that
    // binds it to the pinned release.
    assert!(world.read("seen1.json")?.contains("\"chalk\": \"4.1.1\""));
    assert_eq!(world.read("seen1.lock")?, STARTING);
    assert_eq!(world.read("seen2.json")?, MANIFEST);
    assert!(
        world
            .read("seen2.lock")?
            .contains("\"chalk@npm:4.1.1, chalk@npm:^4.0.0\":"),
        "{}",
        world.read("seen2.lock")?
    );

    // Both installs ran in the copy, under the configured approvals and the target's own.
    let installs = world.installs()?;
    assert_eq!(installs.len(), 2, "{installs:?}");
    for install in &installs {
        assert_ne!(install.directory, world.project.root.as_str());
        assert_eq!(install.preapproved, "left-pad,chalk@4.1.1");
        assert_eq!(install.gate, "");
        assert_eq!(install.global, "");
    }
    // The settled lock was verified in the copy too, after the installs.
    let runs = world.runs()?;
    assert!(
        runs.last().is_some_and(
            |run| run.args == "install --immutable --mode=skip-build --json"
                && run.directory != world.project.root.as_str()
        ),
        "{runs:?}"
    );
    Ok(())
}

/// A downward target lands the same way: the older release is pinned, and the declared range is
/// seeded into its key.
#[tokio::test]
async fn a_downward_landing_seeds_the_older_release() -> eyre::Result<()> {
    let world = new_world(&[("package.json", MANIFEST)], SETTLED)?;
    world.answer("lock1", &PINNED.replace("4.1.1", "4.1.0"))?;
    world.answer("lock2", STARTING)?;
    let change = Change {
        from: Version::new("4.1.1"),
        to: Version::new("4.1.0"),
        downgrade: true,
        ..chalk_change()
    };

    let report = world
        .apply(&Plan {
            changes: vec![change],
            ..Plan::default()
        })
        .await??;

    assert_eq!(report.applied.len(), 1, "{report:?}");
    assert_eq!(world.lock()?, STARTING);
    assert!(
        world
            .read("seen2.lock")?
            .contains("\"chalk@npm:4.1.0, chalk@npm:^4.0.0\":")
    );
    Ok(())
}

/// The temporary gate is cooldown's window when that is stricter than Yarn's, rounded up to whole
/// minutes, and Yarn's own when that is stricter; a Yarn without the gate gets neither setting
/// and is never asked for it.
#[tokio::test]
async fn the_gate_is_raised_to_the_window_only_where_yarn_has_one() -> eyre::Result<()> {
    // A seven-day window beside Yarn's one-day default
    let mut world = single_world()?;
    world.project.exclude_newer = Some("7 days".to_string());
    world.apply(&chalk_plan()).await??;
    let installs = world.installs()?;
    assert!(
        installs.iter().all(|install| install.gate == "10080"),
        "{installs:?}"
    );

    // A stricter native gate
    let mut world = single_world()?;
    world.project.exclude_newer = Some("7 days".to_string());
    Config {
        gate: 20160,
        ..Config::defaults(&world.top)
    }
    .write(&world.top)?;
    world.apply(&chalk_plan()).await??;
    let installs = world.installs()?;
    assert!(
        installs.iter().all(|install| install.gate.is_empty()),
        "{installs:?}"
    );

    // A Yarn before the gate
    let mut world = single_world()?;
    world.project.exclude_newer = Some("7 days".to_string());
    world.answer("version", "4.9.0\n")?;
    world.apply(&chalk_plan()).await??;
    let installs = world.installs()?;
    assert!(
        installs
            .iter()
            .all(|install| install.gate.is_empty() && install.preapproved.is_empty()),
        "{installs:?}"
    );
    Ok(())
}

/// A freeze becomes the age since its instant, rounded up so the gate never admits a release
/// published after it; a window that refuses nothing sets no gate.
#[test]
fn the_floor_is_the_windows_age_rounded_up() -> eyre::Result<()> {
    let now: jiff::Timestamp = "2026-11-04T12:00:30Z".parse()?;
    assert_eq!(floor_minutes(Some("7 days"), now), Some(10080));
    assert_eq!(floor_minutes(Some("2026-11-04T12:00:00Z"), now), Some(1));
    assert_eq!(floor_minutes(Some("2026-11-04T11:59:00Z"), now), Some(2));
    assert_eq!(floor_minutes(None, now), None);
    assert_eq!(floor_minutes(Some("2026-11-05T00:00:00Z"), now), None);
    Ok(())
}

/// A global folder inside a package tree would take Yarn's metadata cache and mirror writes into
/// it, so the installs get one in the scratch directory instead: one inside the project, one
/// inside another tree holding a `package.json`, as the project a preview copied is, whether it
/// exists yet or is reached through a link; one outside every package tree stays the user's.
#[tokio::test]
async fn a_global_folder_inside_a_package_tree_moves_into_the_scratch() -> eyre::Result<()> {
    use std::os::unix::fs::symlink;
    for (global, isolated) in [
        ("{root}/.yarn/berry", true),
        ("{top}/original/.data/yarn/berry", true),
        ("{top}/original/.data/new/yarn/berry", true),
        ("{top}/link/yarn/berry", true),
        ("{top}/global", false),
    ] {
        let world = single_world()?;
        write(&world.top.join("original/package.json"), "{}")?;
        std::fs::create_dir_all(world.top.join("original/.data/yarn/berry"))?;
        symlink(world.top.join("original/.data"), world.top.join("link"))?;
        let global = global
            .replace("{root}", world.project.root.as_str())
            .replace("{top}", world.top.as_str());
        Config {
            global: global.clone(),
            ..Config::defaults(&world.top)
        }
        .write(&world.top)?;

        world.apply(&chalk_plan()).await??;

        let installs = world.installs()?;
        assert_eq!(installs.len(), 2);
        for install in &installs {
            if isolated {
                assert!(
                    !install.global.is_empty()
                        && install.global != global
                        && !Utf8Path::new(&install.global).starts_with(&world.project.root)
                        && !Utf8Path::new(&install.global).starts_with(world.top.join("original")),
                    "{global}: {installs:?}"
                );
            } else {
                assert_eq!(install.global, "", "{global}: {installs:?}");
            }
        }
    }
    Ok(())
}

/// A Yarn that gates each configured scope by the scope's own gate ignores the raised global
/// gate there, so a landing that newly resolves a release of a scope gated below the window fails
/// instead of committing a release no gate held to it; a scope gated at least as strictly passes.
#[tokio::test]
async fn a_new_release_under_a_weaker_scope_gate_fails_the_landing() -> eyre::Result<()> {
    let scoped = SETTLED.replace(
        "      checksum: 10c0/3866c8b96e\n",
        "      dependencies:\n        \"@corp/child\": \"npm:^1.0.0\"\n      checksum: 10c0/3866c8b96e\n",
    ) + indoc! {r#"

        "@corp/child@npm:^1.0.0":
          version: 1.2.0
          resolution: "@corp/child@npm:1.2.0"
          languageName: node
          linkType: hard
    "#};
    for (scope_gate, lands) in [(1440, false), (20160, true)] {
        let mut world = single_world()?;
        world.project.exclude_newer = Some("7 days".to_string());
        world.answer("lock2", &scoped)?;
        Config {
            scopes: serde_json::json!({ "corp": { "npmRegistryServer": "https://npm.corp.example", "npmMinimalAgeGate": scope_gate } }),
            ..Config::defaults(&world.top)
        }
        .write(&world.top)?;

        let report = world.apply(&chalk_plan()).await??;

        assert_eq!(report.applied.len() == 1, lands, "{scope_gate}: {report:?}");
        if lands {
            assert_eq!(world.lock()?, scoped);
        } else {
            assert!(
                matches!(report.skipped.as_slice(), [skipped] if skipped.reason == SkipReason::ResolverConflict),
                "{report:?}"
            );
            assert_eq!(world.lock()?, STARTING);
        }
    }
    Ok(())
}

/// The target the landing approves is cooldown's own choice, so only another release newly
/// resolved in a weakly gated scope fails the guard, and only below the window's floor.
