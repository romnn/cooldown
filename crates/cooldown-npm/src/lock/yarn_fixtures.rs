//! Real Yarn Classic workspaces the Yarn readers' tests share.
//!
//! Each was written by `yarn install --ignore-scripts --non-interactive` (Yarn 1.22.22, run as
//! `node .../corepack/v1/yarn/1.22.22/bin/yarn.js` against registry.yarnpkg.com) in a scratch
//! directory holding exactly the manifests listed beside it.
//! Only the `integrity` lines are elided; every other line, the `resolved` checksums included, is
//! Yarn's own output.

use indoc::indoc;

/// A workspace as its fixture records it: the manifests Yarn read and the lock it wrote.
pub(crate) struct YarnWorkspace {
    /// Each `package.json` as `(project-relative path, contents)`, the root's first.
    pub(crate) manifests: &'static [(&'static str, &'static str)],
    /// The `yarn.lock` Yarn wrote for them.
    pub(crate) lock: &'static str,
}

