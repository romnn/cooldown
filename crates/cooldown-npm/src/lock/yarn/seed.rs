//! Selector seeding: binding the selectors a Yarn Classic landing's members request to one
//! release.
//!
//! Yarn Classic reuses the entry its lock records under a selector and resolves a selector it
//! lacks to the newest release the range admits, so the entry of a target below that maximum comes
//! from an install under a temporary exact pin ([`entry`]).
//! [`seed`] then takes each selected selector out of the key that lists it in the starting lock
//! and keys a copy of that entry by them, so every other selector keeps its entry.
//! Only those entries change, and every other byte of the lock stays as written; the install
//! that follows rewrites the lock in Yarn's canonical form.
//!
//! Entries are found where Yarn's own reader finds them ([`read_items`]), so a blank line or a
//! comment inside an entry stays with it.

use super::{Item, read_items};

/// The lines, each with its line ending, of the entry `lock` keys by `selector`, its key line
/// left out, or `None` when no entry lists the selector or Yarn's reader would not read the lock.
pub(crate) fn entry(lock: &str, selector: &str) -> Option<String> {
    let lines = lines(lock);
    let item = read_items(lock)?
        .into_iter()
        .find(|item| item.keys.iter().any(|key| key == selector))?;
    let body = lines
        .iter()
        .take(item.lines.end() + 1)
        .skip(item.lines.start() + 1);
    Some(body.copied().collect())
}

/// `lock` with each of `selectors` taken out of the key that lists it, and a last entry of
/// `body`'s lines keyed by them alone, or `None` when Yarn's reader would not read the lock.
///
/// A key left listing nothing goes with its entry.
/// The new lines take the lock's line ending.
pub(crate) fn seed(lock: &str, selectors: &[String], body: &str) -> Option<String> {
    let newline = if lock.contains("\r\n") { "\r\n" } else { "\n" };
    let mut lines: Vec<Option<String>> = lines(lock)
        .into_iter()
        .map(|line| Some(line.to_string()))
        .collect();
    for Item {
        keys, lines: span, ..
    } in read_items(lock)?
    {
        if !keys.iter().any(|key| selectors.contains(key)) {
            continue;
        }
        let kept: Vec<&String> = keys.iter().filter(|key| !selectors.contains(key)).collect();
        let mut span_lines = lines.iter_mut().take(span.end() + 1).skip(*span.start());
        if kept.is_empty() {
            span_lines.for_each(|line| *line = None);
        } else if let Some(key_line) = span_lines.next() {
            *key_line = Some(format!("{}{newline}", key_line_of(kept)?));
        }
    }
    let mut seeded = String::new();
    if lock.starts_with('\u{feff}') {
        seeded.push('\u{feff}');
    }
    seeded.extend(lines.into_iter().flatten());
    if !seeded.ends_with('\n') {
        seeded.push_str(newline);
    }
    seeded.push_str(newline);
    seeded.push_str(&key_line_of(selectors)?);
    seeded.push_str(newline);
    for line in body.lines() {
        seeded.push_str(line);
        seeded.push_str(newline);
    }
    Some(seeded)
}

/// The lines of `lock` after any byte-order mark, each with its line ending, numbered as Yarn's
/// reader numbers them.
fn lines(lock: &str) -> Vec<&str> {
    lock.strip_prefix('\u{feff}')
        .unwrap_or(lock)
        .split_inclusive('\n')
        .collect()
}

/// The key line listing `keys`, each quoted, without its line ending.
fn key_line_of<'a>(keys: impl IntoIterator<Item = &'a String>) -> Option<String> {
    let keys: Vec<String> = keys
        .into_iter()
        .map(serde_json::to_string)
        .collect::<Result<_, _>>()
        .ok()?;
    Some(format!("{}:", keys.join(", ")))
}

#[cfg(test)]
mod tests {
    use super::{entry, seed};
    use indoc::indoc;

    /// The lock a starting landing reads, written with a byte-order mark and `\r\n` line
    /// endings: `supports-color@^7.0.0`, the root's, grouped with `chalk`'s own `^7.1.0` under
    /// 7.1.0, below a comment of its own.
    fn starting() -> String {
        let lock = indoc! {r#"
            # THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
            # yarn lockfile v1


            "@scope/pkg@^1.0.0":
              version "1.0.0"

            # kept as written
            supports-color@^7.0.0, supports-color@^7.1.0:
              version "7.1.0"
              dependencies:
                has-flag "^4.0.0"
        "#};
        format!("\u{feff}{}", lock.replace('\n', "\r\n"))
    }

    /// Seeding the root's selector splits the grouped key: the root's selector alone takes the
    /// pinned release's entry, every field as Yarn wrote it, while `chalk`'s keeps 7.1.0, and
    /// every other byte, the byte-order mark, the comments, and the line endings included, stays.
    #[test]
    fn seeding_rewrites_only_the_grouped_key() {
        let pinned = indoc! {r#"
            supports-color@7.2.0:
              version "7.2.0"
              integrity sha512-abc
              dependencies:
                has-flag "^4.0.0"
        "#};
        let body = entry(pinned, "supports-color@7.2.0").expect("the pinned entry");

        let seeded = seed(&starting(), &["supports-color@^7.0.0".to_string()], &body)
            .expect("a readable lock");

        let expected = indoc! {r#"
            # THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
            # yarn lockfile v1


            "@scope/pkg@^1.0.0":
              version "1.0.0"

            # kept as written
            "supports-color@^7.1.0":
              version "7.1.0"
              dependencies:
                has-flag "^4.0.0"

            "supports-color@^7.0.0":
              version "7.2.0"
              integrity sha512-abc
              dependencies:
                has-flag "^4.0.0"
        "#};
        assert_eq!(
            seeded,
            format!("\u{feff}{}", expected.replace('\n', "\r\n"))
        );
    }

    /// An entry ends where Yarn's reader ends it, not at a blank line inside it: its pinned entry
    /// keeps every field, and a sole key's entry goes whole when its selector is seeded.
    #[test]
    fn an_entry_spans_a_blank_line_inside_it() {
        let lock = indoc! {r#"
            # yarn lockfile v1


            chalk@^4.0.0:
              version "4.0.0"

              resolved "https://registry.yarnpkg.com/chalk/-/chalk-4.0.0.tgz"

            leaf@^1.0.0:
              version "1.0.0"
        "#};
        let body = entry(lock, "chalk@^4.0.0").expect("the entry");
        assert_eq!(
            body,
            "  version \"4.0.0\"\n\n  resolved \"https://registry.yarnpkg.com/chalk/-/chalk-4.0.0.tgz\"\n"
        );

        let seeded = seed(lock, &["chalk@^4.0.0".to_string()], "  version \"4.1.0\"\n")
            .expect("a readable lock");

        assert_eq!(
            seeded,
            indoc! {r#"
                # yarn lockfile v1



                leaf@^1.0.0:
                  version "1.0.0"

                "chalk@^4.0.0":
                  version "4.1.0"
            "#}
        );
    }
}
