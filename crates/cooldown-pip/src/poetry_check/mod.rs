//! Proves a `poetry.lock` current with Poetry's own `poetry check --lock`.
//!
//! Poetry refuses a lock whose content hash no longer matches the dependency declarations in
//! `pyproject.toml`, and it neither installs nor writes anything in the project to say so.
//! Its verdict covers the lock only where the probe first establishes that Poetry checks the
//! project cooldown reads:
//!
//! - Poetry is a stable 2.3 or newer, which hashes PEP 735 `[dependency-groups]`;
//! - the project's own `pyproject.toml` sits at its root, since Poetry otherwise walks upward and
//!   checks an enclosing project.
//!
//! The content hash covers the declarations, not what the lock resolved them to.
//! Poetry's exit 0 therefore proves the lock current only when nothing it does not hash can change
//! the resolution, and cooldown evaluates what the lock resolved ([`unproven_by_poetry`]).
//!
//! Every Poetry the probe runs loads no plugins, keeps its cache under cooldown's cache directory,
//! outside the checkout, and runs without writing Python bytecode.
//! The check reads only the manifest and the lock, so it needs no network.

use camino::Utf8Path;
use cooldown_adapter_util::{Driver, canonical_path, outside_project};
use cooldown_core::{
    CoreError, LockStatus, LockVerifyReport, Result, ToolTermination, failure_detail,
};
use cooldown_uv::version;
use std::cmp::Ordering;
use std::process::Output;
use toml::{Table, Value};

const LOCKFILE: &str = "poetry.lock";

const MANIFEST: &str = "pyproject.toml";

/// The oldest Poetry that hashes `[dependency-groups]`.
const MIN_POETRY: &str = "2.3";

/// Poetry's error for a lock whose content hash no longer matches `pyproject.toml`.
const CHANGED: &str = "pyproject.toml changed significantly since poetry.lock was last generated. \
                       Run `poetry lock` to fix the lock file.";

/// Poetry's error for a project without a lock.
const MISSING: &str = "poetry.lock was not found.";

/// The lines Poetry prints after a warning about a `[tool.poetry]` field that may be dynamic, in
/// Poetry 2.3 through 2.5.
const WARNING_CONTINUATIONS: [&str; 3] = [
    "If you want to set the version dynamically via `poetry build --local-version` or you are \
     using a plugin, which sets the version dynamically, you should define the version in \
     [tool.poetry] and add 'version' to [project.dynamic].",
    "If you want to define multiple readmes, you should define them in [tool.poetry] and add \
     'readme' to [project.dynamic].",
    "ATTENTION: Per default Poetry determines classifiers for supported Python versions and \
     license automatically. If you define classifiers in [project], you disable the automatic \
     enrichment. In other words, you have to define all classifiers manually. If you want to use \
     Poetry's automatic enrichment of classifiers, you should define them in [tool.poetry] and \
     add 'classifiers' to [project.dynamic].",
];

/// The flags every probe command runs with, so neither a plugin nor a prompt or color code can
/// change what Poetry checks or prints.
const PINNED_FLAGS: [&str; 3] = ["--no-plugins", "--no-ansi", "--no-interaction"];

/// The prefix of the comment line Poetry opens every lock with, followed by its version.
const GENERATOR: &str = "# This file is automatically @generated by Poetry ";

/// Asks Poetry whether the `poetry.lock` at `root` is current, with Poetry's cache kept under
/// `scratch`.
///
/// The lock is [`LockStatus::Stale`] only when Poetry's sole error is its refusal of a lock that
/// no longer matches `pyproject.toml`, or of a missing lock while no lock exists, beside nothing
/// but warnings.
/// A qualification the probe cannot establish is [`LockStatus::Unknown`].
///
/// # Errors
///
/// Returns [`CoreError::ToolSpawn`] if Poetry cannot be spawned, [`CoreError::Tool`] for any other
/// Poetry failure, [`CoreError::Filesystem`] if the project cannot be read,
/// [`CoreError::LockUnreadable`] for a lock the inventory reader refuses, and [`CoreError::Parse`]
/// for a manifest that is not TOML.
pub(crate) async fn lock_current(
    driver: &Driver,
    root: &Utf8Path,
    scratch: &Utf8Path,
) -> Result<LockVerifyReport> {
    let filesystem =
        |path: &Utf8Path, err: std::io::Error| CoreError::Filesystem(format!("{path}: {err}"));
    let canonical = canonical_path(root).map_err(|err| filesystem(root, err))?;
    let lock_path = canonical.join(LOCKFILE);
    let manifest_path = canonical.join(MANIFEST);

    // Qualify the scope and the cache directory
    if !manifest_path.is_file() {
        return Ok(unknown(&format!(
            "no {MANIFEST} exists at {root}, so Poetry would check an enclosing project"
        )));
    }
    let Some(cache) = outside_project(&canonical, &scratch.join("cache")) else {
        return Ok(unknown(&format!(
            "cooldown's cache directory {scratch} leads into the project, where Poetry would \
             write its cache"
        )));
    };

    // Read the files Poetry compares, so every qualification judges the bytes it checked
    let manifest =
        std::fs::read_to_string(&manifest_path).map_err(|err| filesystem(&manifest_path, err))?;
    let lock = std::fs::read_to_string(&lock_path).ok();

    let poetry = async |args: &[&str]| -> Result<Output> {
        let args: Vec<String> = args
            .iter()
            .chain(&PINNED_FLAGS)
            .map(ToString::to_string)
            .collect();
        let env = [
            ("POETRY_CACHE_DIR", cache.as_str()),
            ("PYTHONDONTWRITEBYTECODE", "1"),
        ];
        driver.output_with_env(&canonical, &args, &env).await
    };

    // Qualify the executable
    let out = poetry(&["--version"]).await?;
    if !out.status.success() {
        return Err(driver.failure(&out));
    }
    let printed = String::from_utf8_lossy(&out.stdout);
    if !supports_check(&printed) {
        return Ok(unknown(&format!(
            "it requires a stable Poetry >= {MIN_POETRY} to verify {LOCKFILE}, and Poetry printed \
             `{}`",
            printed.trim()
        )));
    }

    // Run Poetry's own verification
    let out = poetry(&["check", "--lock"]).await?;
    let termination = ToolTermination::from_exit_status(out.status);
    let stdout = String::from_utf8_lossy(&out.stdout);
    let stderr = String::from_utf8_lossy(&out.stderr);
    match verdict(termination, &stdout, &stderr) {
        Verdict::Passed => {
            // A file rewritten, created, or removed while Poetry ran was never the one compared.
            let unchanged = |path: &Utf8Path, before: &str| {
                std::fs::read_to_string(path).is_ok_and(|after| after == before)
            };
            let Some(lock) = lock
                .filter(|lock| unchanged(&lock_path, lock) && unchanged(&manifest_path, &manifest))
            else {
                return Ok(unknown(&format!(
                    "{LOCKFILE} or {MANIFEST} changed while Poetry verified them"
                )));
            };
            // A project plugin, which a plain Poetry run loads, can change what Poetry resolves.
            if std::fs::symlink_metadata(canonical.join(".poetry").join("plugins")).is_ok() {
                return Ok(unknown(
                    "the project has a `.poetry/plugins` directory, whose plugins Poetry loads",
                ));
            }
            Ok(match unproven_by_poetry(&lock, &manifest)? {
                Some(reason) => unknown(&reason),
                None => LockVerifyReport {
                    status: LockStatus::Current,
                    detail: format!("{LOCKFILE} is current"),
                },
            })
        }
        Verdict::Changed => Ok(stale(root, &out)),
        Verdict::Missing if absent(&lock_path) => Ok(stale(root, &out)),
        Verdict::Missing | Verdict::Failed => Err(driver.failure(&out)),
    }
}

fn unknown(reason: &str) -> LockVerifyReport {
    LockVerifyReport {
        status: LockStatus::Unknown,
        detail: format!("{LOCKFILE} currency cannot be verified: {reason}"),
    }
}

/// The stale verdict, naming the project ahead of Poetry's own message so a repository with
/// several locks knows which one Poetry refused.
fn stale(root: &Utf8Path, out: &Output) -> LockVerifyReport {
    LockVerifyReport {
        status: LockStatus::Stale,
        detail: format!("{LOCKFILE} is stale in {root}: {}", failure_detail(out)),
    }
}

/// Whether nothing exists at `path`, not even a dangling symbolic link, which Poetry also reports
/// as a missing lock.
fn absent(path: &Utf8Path) -> bool {
    matches!(
        std::fs::symlink_metadata(path),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound
    )
}

/// Whether the Poetry that printed `printed` for `--version` is a stable release no older than
/// [`MIN_POETRY`].
///
/// Poetry prints `Poetry (version 2.5.1)`.
/// Releases before 1.2 print `Poetry version 1.1.15` instead, and are too old anyway.
fn supports_check(printed: &str) -> bool {
    printed
        .trim()
        .strip_prefix("Poetry (version ")
        .and_then(|rest| rest.strip_suffix(')'))
        .is_some_and(|release| {
            version::parse(release).is_some()
                && !version::is_prerelease(release)
                && version::compare(release, MIN_POETRY) != Ordering::Less
        })
}

/// What one `poetry check --lock` says about the lock.
#[derive(Debug, PartialEq, Eq)]
enum Verdict {
    /// Poetry exited 0, which it does beside warnings too.
    Passed,
    /// Poetry's refusal of a lock that no longer matches `pyproject.toml` was its sole error.
    Changed,
    /// Poetry's refusal of a missing lock was its sole error.
    Missing,
    /// Any other outcome.
    Failed,
}

/// Reads a check's `termination` and its combined output.
fn verdict(termination: ToolTermination, stdout: &str, stderr: &str) -> Verdict {
    match termination {
        ToolTermination::ExitCode(0) => Verdict::Passed,
        ToolTermination::ExitCode(1) => match sole_error(stdout, stderr) {
            Some(CHANGED) => Verdict::Changed,
            Some(MISSING) => Verdict::Missing,
            _ => Verdict::Failed,
        },
        _ => Verdict::Failed,
    }
}

/// The message of the one `Error:` line in a failed check's output, when every other line is a
/// warning Poetry prints, line endings and trailing whitespace ignored.
///
/// Poetry prints each error as `Error: …` and each warning as `Warning: …` on standard error, and
/// nothing on standard output for a failed check, so any standard output is unrecognised.
/// A warning about a `[tool.poetry]` field that may be dynamic continues on the next line with one
/// of the [`WARNING_CONTINUATIONS`].
/// A warning Poetry finds while it loads the project is also logged as a bare line, which its own
/// `Warning:` line repeats.
/// Any other line is unrecognised output, so no error is returned.
fn sole_error<'a>(stdout: &str, stderr: &'a str) -> Option<&'a str> {
    if !stdout.trim().is_empty() {
        return None;
    }
    let lines: Vec<&str> = stderr
        .lines()
        .map(str::trim_end)
        .filter(|line| !line.is_empty())
        .collect();
    let warnings: Vec<&str> = lines
        .iter()
        .filter_map(|line| line.strip_prefix("Warning: "))
        .collect();
    let mut errors = Vec::new();
    let mut after_warning = false;
    for line in &lines {
        let continuation = after_warning && WARNING_CONTINUATIONS.contains(line);
        after_warning = line.starts_with("Warning: ");
        if let Some(error) = line.strip_prefix("Error: ") {
            errors.push(error);
        } else if !after_warning && !continuation && !warnings.contains(line) {
            return None;
        }
    }
    match errors.as_slice() {
        [error] => Some(error),
        _ => None,
    }
}

/// Why Poetry's exit 0 would not prove the `lock` current against the `manifest`, if it would not.
///
/// The exit proves the lock current only where Poetry's installer reads the lock as the checking
/// Poetry does, nothing the content hash leaves out can change the resolution, and cooldown judges
/// each package by the source it came from:
///
/// - the lock's `lock-version` is a format Poetry's installer reads;
/// - `pyproject.toml` lists no `project.dynamic`, which changes how Poetry combines the
///   `[project]` and `[tool.poetry]` declarations, and requires no plugin;
/// - the lock lists packages whenever the manifest declares one;
/// - no declaration or lock edge has a direct URL, git, or path origin, whose content can change at
///   the same declaration;
/// - every locked package comes from PyPI, whose release cooldown judges, and the manifest
///   declares no other package source;
/// - the Poetry that wrote the lock hashed `[dependency-groups]` the way the checking Poetry
///   compares them ([`groups_hashed`]).
///
/// # Errors
///
/// Returns [`CoreError::LockUnreadable`] if the lock is not TOML or lacks its packages, and
/// [`CoreError::Parse`] if the manifest is not TOML.
fn unproven_by_poetry(lock: &str, manifest: &str) -> Result<Option<String>> {
    let lock_document: Table = toml::from_str(lock)
        .map_err(|err| CoreError::LockUnreadable(format!("{LOCKFILE}: {err}")))?;
    let pins = crate::lock::poetry_lock_pins(&lock_document)?;
    let manifest: Table =
        toml::from_str(manifest).map_err(|err| CoreError::Parse(format!("{MANIFEST}: {err}")))?;
    let lock_version = lock_document
        .get("metadata")
        .and_then(|metadata| metadata.get("lock-version"))
        .and_then(Value::as_str);
    let poetry = manifest.get("tool").and_then(|tool| tool.get("poetry"));

    if !lock_version.is_some_and(readable_format) {
        return Ok(Some(format!(
            "{LOCKFILE} records no `lock-version` Poetry's installer reads; run `poetry lock`"
        )));
    }
    if manifest
        .get("project")
        .and_then(|project| project.get("dynamic"))
        .is_some()
    {
        return Ok(Some(format!(
            "{MANIFEST} lists `project.dynamic`, which changes how Poetry combines its \
             declarations"
        )));
    }
    if poetry.is_some_and(|poetry| poetry.get("requires-plugins").is_some()) {
        return Ok(Some(format!(
            "{MANIFEST} lists `tool.poetry.requires-plugins`, whose plugins Poetry loads"
        )));
    }
    if pins.is_empty() && !crate::lock::poetry_declared(&manifest).is_empty() {
        return Ok(Some(format!(
            "{LOCKFILE} lists no packages while {MANIFEST} declares some; run `poetry lock`"
        )));
    }
    if let Some(reason) = direct_origin(&manifest, &lock_document) {
        return Ok(Some(reason));
    }
    if let Some(pin) = pins.iter().find(|pin| !pin.pypi) {
        return Ok(Some(format!(
            "{LOCKFILE} takes `{}` from a source other than PyPI, while cooldown judges PyPI's \
             release",
            pin.name
        )));
    }
    if crate::ambient::declares_sources(&manifest) {
        return Ok(Some(format!(
            "{MANIFEST} declares a `[[tool.poetry.source]]`, while cooldown judges PyPI's \
             releases"
        )));
    }
    let declares_groups = manifest
        .get("dependency-groups")
        .is_some_and(|groups| groups.as_table().is_none_or(|groups| !groups.is_empty()));
    if !groups_hashed(generator(lock), lock_version, declares_groups) {
        return Ok(Some(format!(
            "{LOCKFILE} was written by a Poetry whose content hash does not cover \
             `[dependency-groups]` as Poetry {MIN_POETRY} and newer compare it; run `poetry lock`"
        )));
    }
    Ok(None)
}

/// Whether Poetry's installer reads a lock of format `lock_version`, a stable version it accepts
/// from 1 up to but excluding 3, refusing the lock otherwise while its freshness check still
/// passes it.
fn readable_format(lock_version: &str) -> bool {
    version::parse(lock_version).is_some()
        && !version::is_prerelease(lock_version)
        && version::compare(lock_version, "1") != Ordering::Less
        && version::compare(lock_version, "3") == Ordering::Less
}

/// The Poetry version the lock's opening comment names, if it names one.
fn generator(lock: &str) -> Option<&str> {
    lock.lines()
        .next()?
        .strip_prefix(GENERATOR)?
        .split_whitespace()
        .next()
}

/// Whether the content hash of a lock written by Poetry `generator` covers `[dependency-groups]`
/// as the checking Poetry compares it.
///
/// Poetry 2.3 and newer compare a lock written by an older Poetry against a content hash without
/// the groups, which older releases did not hash, so a change to them goes unseen:
///
/// - Poetry 2.2 resolved the groups into its locks, so none of its locks is proven;
/// - Poetry before 2.2 ignored them, so its lock is proven only while no group is declared;
/// - a lock without a readable generator is proven only when its `lock-version` predates 2.1,
///   which only Poetry before 2.0 wrote, and no group is declared.
fn groups_hashed(
    generator: Option<&str>,
    lock_version: Option<&str>,
    declares_groups: bool,
) -> bool {
    let at_least = |release: &str, floor: &str| version::compare(release, floor) != Ordering::Less;
    match generator.filter(|release| version::parse(release).is_some()) {
        Some(release) if at_least(release, MIN_POETRY) => true,
        Some(release) if at_least(release, "2.2") => false,
        Some(_) => !declares_groups,
        None => {
            !declares_groups
                && lock_version.is_some_and(|lock_version| {
                    version::parse(lock_version).is_some() && !at_least(lock_version, "2.1")
                })
        }
    }
}

/// Why the `manifest`'s declarations or the `lock`'s dependency edges name a direct URL, git, or
/// path origin, if any does.
///
/// A locked package from such an origin records a `source`, which the PyPI-only rule refuses.
fn direct_origin(manifest: &Table, lock: &Table) -> Option<String> {
    let reason = |file: &str, name: &str| {
        format!(
            "{file} names a URL, git, or path origin for `{name}`, whose content Poetry's check \
             does not compare"
        )
    };
    for table in crate::lock::poetry_dependency_tables(manifest) {
        if let Some((name, _)) = table.iter().find(|(_, spec)| is_direct_spec(spec)) {
            return Some(reason(MANIFEST, name));
        }
    }
    for list in crate::lock::requirement_lists(manifest) {
        let direct = list
            .iter()
            .filter_map(Value::as_str)
            .find(|requirement| is_direct_reference(requirement));
        if let Some(requirement) = direct {
            return Some(reason(MANIFEST, requirement));
        }
    }
    let packages = lock.get("package").and_then(Value::as_array)?;
    packages.iter().find_map(|package| {
        let edges = package.get("dependencies").and_then(Value::as_table)?;
        edges
            .iter()
            .find(|(_, spec)| is_direct_spec(spec))
            .map(|(dependency, _)| reason(LOCKFILE, dependency))
    })
}

/// Whether a Poetry dependency specification, or any of its multiple-constraint entries, takes the
/// package from a git repository, a URL, or a path.
fn is_direct_spec(spec: &Value) -> bool {
    match spec {
        Value::Table(table) => ["git", "url", "path"]
            .iter()
            .any(|key| table.contains_key(*key)),
        Value::Array(entries) => entries.iter().any(is_direct_spec),
        _ => false,
    }
}

/// Whether a PEP 508 requirement is a direct reference (`name @ url`), whose `@` can only appear
/// ahead of the environment marker.
fn is_direct_reference(requirement: &str) -> bool {
    requirement
        .split_once(';')
        .map_or(requirement, |(specification, _)| specification)
        .contains('@')
}

